-- This table holds a single row that the scheduling service locks
-- while checking for conflicts and writing a booking.
CREATE TABLE IF NOT EXISTS booking_lock (
    id INT PRIMARY KEY
);

-- Ensure the lock row exists each time the service starts.
MERGE INTO booking_lock KEY(id) VALUES (1);

-- Store the operating room, equipment, and recovery bed in one booking.
-- The room and equipment are reserved from starts to ends.
-- The bed is reserved from ends to recovery_ends.
CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INT NOT NULL,
    room VARCHAR(32) NOT NULL,
    bed VARCHAR(32) NOT NULL,
    equipment VARCHAR(32) NOT NULL,
    starts TIMESTAMP WITH TIME ZONE NOT NULL,
    ends TIMESTAMP WITH TIME ZONE NOT NULL,
    recovery_ends TIMESTAMP WITH TIME ZONE NOT NULL,

    -- Keep cancelled bookings in the database while freeing their resources.
    cancelled BOOLEAN DEFAULT FALSE NOT NULL
);